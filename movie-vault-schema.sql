-- Midnight Archive movie database schema (deployed to BBB Supabase 2026-11-19).
-- Ratings and reviews are readable by anyone with the archive URL.
-- Write access is restricted by auth.uid() to two existing, explicitly identified owner accounts.
-- The original 17 movie payloads are preserved in movie-vault.html and seeded in the live DB.
-- This is a repository copy of the deployed schema for maintenance; not a Supabase CLI migration.
CREATE TABLE IF NOT EXISTS public.midnight_archive_films (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payload jsonb NOT NULL,
  watched_on date NULL,
  watch_order integer NOT NULL,
  created_by uuid DEFAULT auth.uid(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT midnight_archive_payload_valid CHECK (
    jsonb_typeof(payload) = 'object'
    AND length(btrim(payload->>'title')) BETWEEN 1 AND 180
    AND jsonb_typeof(payload->'b') = 'number'
    AND jsonb_typeof(payload->'l') = 'number'
    AND (payload->>'b')::numeric BETWEEN 0 AND 10
    AND (payload->>'l')::numeric BETWEEN 0 AND 10
    AND (payload->>'year') ~ '^[0-9]{4}$'
    AND (payload->>'year')::integer BETWEEN 1880 AND 2200
    AND jsonb_typeof(payload->'br') = 'string'
    AND jsonb_typeof(payload->'lr') = 'string'
  )
);
